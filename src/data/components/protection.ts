import type { ComponentSource, PathSpec } from '@/types/component';
import { POLES_1P, POLES_1PN, POLES_3P, POLES_3PN, poleDevice, spec, term, type Pole } from './factories';

function breaker(
  p: {
    type: string;
    name: string;
    poles: Pole[];
    glyph: 'breaker' | 'rccb' | 'switch';
    text?: string;
    description: string;
    fn: string;
    specs: ComponentSource['specs'];
    phase: number;
    tags?: string[];
    designator?: string;
  },
): ComponentSource {
  const { terminals, pairs } = poleDevice(p.poles);
  const paths: PathSpec[] = pairs.map((pair) => ({ glyph: p.glyph, terminals: pair }));
  return {
    type: p.type,
    name: p.name,
    category: 'protection',
    designator: p.designator ?? 'Q',
    description: p.description,
    function: p.fn,
    symbol: { kind: 'paths', paths, ...(p.text ? { text: p.text } : {}) },
    terminals,
    specs: p.specs,
    simulationPhase: p.phase,
    ...(p.tags ? { tags: p.tags } : {}),
  };
}

